class AppStrings(
    val language: ResolvedLanguage,
    val table: Map<Str, String>,
) {
    operator fun get(key: Str): String = table.getValue(key)

    fun format(key: Str, vararg args: Any?): String {
        var text = table.getValue(key)
        for (i in args.indices) {
            text = text.replace("{$i}", args[i]?.toString().orEmpty())
        }
        return text
    }

    fun itemsCount(count: Int): String =
        if (count == 1) get(Str.ITEMS_SINGLE) else format(Str.ITEMS_PLURAL, count)

    fun filesCount(count: Int): String =
        if (count == 1) get(Str.FILES_SINGLE) else format(Str.FILES_PLURAL, count)

    fun foldersCount(count: Int): String =
        if (count == 1) get(Str.FOLDERS_SINGLE) else format(Str.FOLDERS_PLURAL, count)

    fun activeConnections(count: Int): String =
        if (count == 1) get(Str.SVC_ACTIVE_CONN_SINGLE) else format(Str.SVC_ACTIVE_CONN_PLURAL, count)

    fun activeRequests(count: Int): String =
        if (count == 1) get(Str.SVC_ACTIVE_REQ_SINGLE) else format(Str.SVC_ACTIVE_REQ_PLURAL, count)

    fun clientsCount(count: Int): String =
        if (count == 1) get(Str.SVC_CLIENTS_SINGLE) else format(Str.SVC_CLIENTS_PLURAL, count)
}

object AppI18n {
    private val stringsByLang: Map<ResolvedLanguage, AppStrings> by lazy {
        mapOf(
            ResolvedLanguage.EN to AppStrings(ResolvedLanguage.EN, APP_STRINGS_EN),
            ResolvedLanguage.ZH to AppStrings(ResolvedLanguage.ZH, APP_STRINGS_ZH),
            ResolvedLanguage.JA to AppStrings(ResolvedLanguage.JA, APP_STRINGS_JA),
        )
    }

    private val _setting = MutableStateFlow(AppLanguage.SYSTEM)
    val currentSetting: StateFlow<AppLanguage> = _setting.asStateFlow()

    private val _currentLanguage = MutableStateFlow(resolve(AppLanguage.SYSTEM, Locale.getDefault()))
    val currentLanguage: StateFlow<ResolvedLanguage> = _currentLanguage.asStateFlow()

    fun resolve(setting: AppLanguage, systemLocale: Locale = Locale.getDefault()): ResolvedLanguage =
        when (setting) {
            AppLanguage.ZH -> ResolvedLanguage.ZH
            AppLanguage.EN -> ResolvedLanguage.EN
            AppLanguage.JA -> ResolvedLanguage.JA
            AppLanguage.SYSTEM -> resolveFromLanguageCode(systemLocale.language)
        }

    fun resolveLanguageTag(setting: AppLanguage, languageTag: String?): ResolvedLanguage =
        when (setting) {
            AppLanguage.ZH -> ResolvedLanguage.ZH
            AppLanguage.EN -> ResolvedLanguage.EN
            AppLanguage.JA -> ResolvedLanguage.JA
            AppLanguage.SYSTEM -> {
                val primary = languageTag
                    ?.trim()
                    ?.substringBefore('-')
                    ?.substringBefore('_')
                    .orEmpty()
                resolveFromLanguageCode(primary)
            }
        }

    private fun resolveFromLanguageCode(code: String?): ResolvedLanguage {
        val norm = code?.trim()?.lowercase(Locale.ROOT).orEmpty()
        return when {
            norm == "zh" -> ResolvedLanguage.ZH
            norm == "ja" -> ResolvedLanguage.JA
            else -> ResolvedLanguage.EN
        }
    }

    fun setSetting(setting: AppLanguage, systemLocale: Locale = Locale.getDefault()) {
        _setting.value = setting
        _currentLanguage.value = resolve(setting, systemLocale)
    }

    fun setResolved(setting: AppLanguage, resolved: ResolvedLanguage) {
        _setting.value = setting
        _currentLanguage.value = resolved
    }

    fun onSystemLocaleChanged(systemLocale: Locale = Locale.getDefault()) {
        _currentLanguage.value = resolve(_setting.value, systemLocale)
    }

    fun stringsFor(language: ResolvedLanguage): AppStrings = stringsByLang.getValue(language)

    /** `true` when [message] is a Google Drive / Google sign-in expiry error in any supported language. */
    fun isSignInExpiredMessage(message: String?): Boolean {
        if (message.isNullOrBlank()) return false
        if (message.contains("sign-in expired", ignoreCase = true)) return true
        val keys = listOf(Str.GDRIVE_SIGNIN_EXPIRED, Str.GDRIVE_SIGNIN_EXPIRED_AGAIN, Str.GOOGLE_SIGNIN_EXPIRED_AGAIN)
        return ResolvedLanguage.entries.any { lang ->
            val strings = stringsFor(lang)
            keys.any { key -> message.contains(strings[key]) }
        }
    }

    fun current(): AppStrings = stringsFor(_currentLanguage.value)
}
